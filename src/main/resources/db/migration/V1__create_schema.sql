CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE job_applications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    company    VARCHAR(200) NOT NULL,
    role       VARCHAR(200) NOT NULL,
    url        VARCHAR(2048),
    location   VARCHAR(200),
    status     VARCHAR(20) NOT NULL,
    applied_on DATE,
    notes      VARCHAR(5000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_job_applications_user ON job_applications (user_id, updated_at);

CREATE TABLE status_changes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES job_applications (id) ON DELETE CASCADE,
    from_status    VARCHAR(20),
    to_status      VARCHAR(20) NOT NULL,
    changed_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_status_changes_application ON status_changes (application_id);

CREATE TABLE interviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES job_applications (id) ON DELETE CASCADE,
    stage          VARCHAR(20) NOT NULL,
    outcome        VARCHAR(20) NOT NULL,
    scheduled_at   TIMESTAMP WITH TIME ZONE,
    notes          VARCHAR(2000)
);
CREATE INDEX idx_interviews_application ON interviews (application_id);

CREATE TABLE reminders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES job_applications (id) ON DELETE CASCADE,
    remind_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    message        VARCHAR(500) NOT NULL,
    sent_at        TIMESTAMP WITH TIME ZONE,
    attempts       INTEGER NOT NULL
);
CREATE INDEX idx_reminders_due ON reminders (sent_at, remind_at);
